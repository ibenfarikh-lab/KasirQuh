function tandaiChatRumpiSudahDibaca() {

  let latestTimestamp =
    adminChatRumpiLastRead;

  db.collection("db_chat_rumpi")
    .orderBy("waktuTimestamp", "desc")
    .limit(1)
    .get()
    .then(snapshot => {

      snapshot.forEach(doc => {

        const data = doc.data();

        const ts =
          data.waktuTimestamp;

        if (ts) {

          latestTimestamp =
            ts.toMillis
              ? ts.toMillis()
              : Number(ts);

        }

      });

      adminChatRumpiLastRead =
        latestTimestamp;

      localStorage.setItem(
        "chatRumpiLastRead",
        adminChatRumpiLastRead
      );

      updateBadgeChatRumpi(0);

    })
    .catch(err => {

      console.error(
        "Gagal menandai Chat Rumpi:",
        err
      );

    });

}


