function cekStatusLogin() {

  if (
    localStorage.getItem("isLoggedIn") ===
    "true"
  ) {

    const loginModal =
      document.getElementById("loginModal");

    if (loginModal) {
      loginModal.style.display = "none";
    }

  } else {

    const loginModal =
      document.getElementById("loginModal");

    if (loginModal) {
      loginModal.style.display = "flex";
    }

  }

}


