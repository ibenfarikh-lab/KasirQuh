function convertImgToBase64(
  url,
  callback
) {
  const img =
    new Image();

  img.crossOrigin =
    'Anonymous';

  img.onload =
    function() {

      const canvas =
        document.createElement(
          'canvas'
        );

      const ctx =
        canvas.getContext(
          '2d'
        );

      canvas.width =
        120;

      canvas.height =
        120;

      ctx.drawImage(
        img,
        0,
        0,
        120,
        120
      );

      callback(
        canvas.toDataURL(
          'image/jpeg',
          0.7
        )
      );
    };

  img.src =
    url;
}

