function handleImageUpload(event) {
  const file =
    event.target.files[0];

  if (!file) return;

  const reader =
    new FileReader();

  reader.onload =
    function(e) {

      const img =
        new Image();

      img.onload =
        function() {

          const canvas =
            document.createElement(
              'canvas'
            );

          const ctx =
            canvas.getContext(
              '2d'
            );

          let width =
            img.width;

          let height =
            img.height;

          const maxSize =
            300;

          if (width > height) {

            if (width > maxSize) {

              height *=
                maxSize / width;

              width =
                maxSize;
            }

          } else {

            if (height > maxSize) {

              width *=
                maxSize / height;

              height =
                maxSize;
            }
          }

          canvas.width =
            width;

          canvas.height =
            height;

          ctx.drawImage(
            img,
            0,
            0,
            width,
            height
          );

          const compressedBase64 =
            canvas.toDataURL(
              'image/jpeg',
              0.7
            );

          document.getElementById(
            "db-selected-online-img"
          ).value =
            compressedBase64;

          showNotif(
            "Foto berhasil dimuat!"
          );
        };

      img.src =
        e.target.result;
    };

  reader.readAsDataURL(file);
}

