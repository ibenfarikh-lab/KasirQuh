function simpanPengaturanAkun() {
  const user = auth.currentUser;
  const email = document.getElementById("setting-user").value.trim();
  const password = document.getElementById("setting-pass").value;

  if (!user) return alert("Silakan login terlebih dahulu.");
  if (!email) return alert("Email tidak boleh kosong!");

  const perubahan = [];

  if (email !== (user.email || "")) {
    perubahan.push(
      user.updateEmail(email).catch(err => {
        if (err.code === "auth/requires-recent-login") {
          throw new Error("Untuk mengganti email, silakan logout lalu login kembali, kemudian coba lagi.");
        }
        throw err;
      })
    );
  }

  if (password) {
    if (password.length < 6) return alert("Password minimal 6 karakter.");
    perubahan.push(
      user.updatePassword(password).catch(err => {
        if (err.code === "auth/requires-recent-login") {
          throw new Error("Untuk mengganti password, silakan logout lalu login kembali, kemudian coba lagi.");
        }
        throw err;
      })
    );
  }

  if (!perubahan.length) return alert("Tidak ada perubahan akun.");

  Promise.all(perubahan)
    .then(() => {
      return db.collection("pengguna").doc(user.uid).set({
        role: "admin",
        tokoId: "toko_v13",
        email: email,
        updatedAt: firebase.firestore.FieldValue.serverTimestamp()
      }, { merge: true });
    })
    .then(() => {
      document.getElementById("setting-pass").value = "";
      alert("Akun login berhasil diperbarui di Firebase Authentication.");
      refreshData();
    })
    .catch(err => alert("Gagal memperbarui akun: " + err.message));
}

