let catatanListeners = {};

function setupCatatanListener(tabKey) {
  const docId =
    `${tabKey}_${selectedCatatanDate}`;

  if (catatanListeners[tabKey]) {
    catatanListeners[tabKey]();
    catatanListeners[tabKey] = null;
  }

  catatanListeners[tabKey] =
    db.collection("catatan")
      .doc(docId)
      .onSnapshot(
        async (docSnap) => {

          if (docSnap.exists) {

            databaseCatatanDinamis[tabKey] =
              docSnap.data();

            renderHalamanSubCatatan(tabKey);

          } else {

            let currDate =
              new Date(
                selectedCatatanDate +
                "T00:00:00"
              );

            currDate.setDate(
              currDate.getDate() - 1
            );

            let prevDateStr =
              currDate.getFullYear() +
              '-' +
              String(
                currDate.getMonth() + 1
              ).padStart(2, '0') +
              '-' +
              String(
                currDate.getDate()
              ).padStart(2, '0');

            let prevDocId =
              `${tabKey}_${prevDateStr}`;

            let prevDocSnap =
              await db.collection("catatan")
                .doc(prevDocId)
                .get();

            let targetItems = [];

            if (
              prevDocSnap.exists &&
              prevDocSnap.data().items
            ) {

              targetItems =
                prevDocSnap.data().items.map(item => ({
                  id:
                    "NOTE-" +
                    Date.now() +
                    Math.random()
                      .toString(36)
                      .substr(2, 3),

                  judul: item.judul || "",
                  subjudul: "",
                  isi: "",
                  waktu:
                    new Date()
                      .toLocaleString('id-ID')
                }));

            } else {

              let defaultLabel =
                labelNamaTabCatatan[tabKey] ||
                tabKey;

              targetItems = [
                {
                  id: "NOTE-" + Date.now(),
                  judul: defaultLabel,
                  subjudul: "",
                  isi: "",
                  waktu:
                    new Date()
                      .toLocaleString('id-ID')
                }
              ];
            }

            let targetData = {
              tabKey: tabKey,
              tanggal: selectedCatatanDate,
              modalAwal: "0",
              items: targetItems
            };

            await db.collection("catatan")
              .doc(docId)
              .set(targetData);
          }

        },
        err => {
          console.error(
            "Gagal memuat catatan: ",
            err
          );
        }
      );
}

