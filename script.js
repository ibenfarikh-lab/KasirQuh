function hitungRingkasanCatatanDinamis(tabKey) {
  let inputEl =
    document.getElementById(
      `modal-awal-${tabKey}`
    );

  if (!inputEl) return;

  let modalAwal =
    parseRupiahToNumber(
      inputEl.value
    );

  let totalPembayaran = 0;

  let dataObj =
    databaseCatatanDinamis[tabKey];

  if (
    dataObj &&
    dataObj.items
  ) {

    dataObj.items.forEach(item => {

      if (item.subjudul) {

        let subLower =
          item.subjudul.toLowerCase();

        let parts =
          subLower.split('pembayaran');

        if (parts.length > 1) {

          let angkaBayar =
            parseRupiahToNumber(
              parts[1]
            );

          totalPembayaran +=
            angkaBayar;

        } else {

          let matches =
            item.subjudul.match(
              /\b[\d\.]+\b/g
            );

          if (matches) {

            let angkaTerakhir =
              parseRupiahToNumber(
                matches[
                  matches.length - 1
                ]
              );

            totalPembayaran +=
              angkaTerakhir;
          }
        }
      }
    });
  }

  let sisaModal =
    modalAwal -
    totalPembayaran;

  let lblModal =
    document.getElementById(
      `lbl-modal-${tabKey}`
    );

  let lblBayar =
    document.getElementById(
      `lbl-bayar-${tabKey}`
    );

  let lblSisa =
    document.getElementById(
      `lbl-sisa-${tabKey}`
    );

  if (lblModal) {
    lblModal.innerText =
      modalAwal.toLocaleString('id-ID');
  }

  if (lblBayar) {
    lblBayar.innerText =
      totalPembayaran.toLocaleString('id-ID');
  }

  if (lblSisa) {
    lblSisa.innerText =
      sisaModal.toLocaleString('id-ID');
  }
}

